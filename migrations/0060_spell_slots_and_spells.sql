-- DL-185: spell slots and a spell list on a character.
--
-- character_spell_slots: one row per spell level (1 to 9) that the character has slots for.  max_slots is what the sheet says
-- (set on the character form), used_slots is how many are spent right now (filled and emptied on the character page and in the peek).
-- A level with no slots has no row.  used_slots can never pass max_slots.
-- character_spells: the spell list, in order, like character_attacks.  spell_level 0 is a cantrip.  damage is the same kind of
-- roll an attack has (one kind of die plus a flat bonus, stored normalised, empty when the spell deals no damage).
CREATE TABLE character_spell_slots (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id INTEGER NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    slot_level   INTEGER NOT NULL CHECK (slot_level BETWEEN 1 AND 9),
    max_slots    INTEGER NOT NULL DEFAULT 0 CHECK (max_slots BETWEEN 0 AND 9),
    used_slots   INTEGER NOT NULL DEFAULT 0 CHECK (used_slots >= 0),
    UNIQUE (character_id, slot_level),
    CHECK (used_slots <= max_slots)
);
CREATE INDEX idx_character_spell_slots_character ON character_spell_slots (character_id);
ALTER TABLE character_spell_slots ENABLE ROW LEVEL SECURITY;    -- like every table: no direct access through Supabase's data API

CREATE TABLE character_spells (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id INTEGER NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    position     INTEGER NOT NULL DEFAULT 0,
    name         TEXT NOT NULL,
    spell_level  INTEGER NOT NULL DEFAULT 0 CHECK (spell_level BETWEEN 0 AND 9),
    damage       TEXT NOT NULL DEFAULT '',
    damage_type  TEXT NOT NULL DEFAULT '',
    note         TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_character_spells_character ON character_spells (character_id, position);
ALTER TABLE character_spells ENABLE ROW LEVEL SECURITY;
