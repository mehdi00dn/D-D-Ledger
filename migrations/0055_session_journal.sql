-- Session journal (DL-121): a dated list of session recaps per campaign.  The body is stored like character and campaign
-- notes (a JSON list of sanitised boxes, each optionally hidden from players).  Only the DM writes; members read.
CREATE TABLE IF NOT EXISTS session_journal (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
    title       TEXT NOT NULL,
    played_on   DATE NOT NULL,
    body        TEXT NOT NULL DEFAULT '[]',
    created_by  INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS idx_session_journal_campaign ON session_journal (campaign_id, played_on DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_session_journal_author ON session_journal (created_by);

ALTER TABLE session_journal ENABLE ROW LEVEL SECURITY;           -- like every table: no direct access through Supabase's data API
