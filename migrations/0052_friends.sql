-- Friends and per-element profile visibility (DL-98).
-- One row per pair of people, whichever way round they are written (user_low < user_high), so a pair can never be
-- stored twice.  'pending': requested_by asked, the other has not answered.  'accepted': friends.  'blocked': requested_by
-- is the person who blocked the other.  Friendship is never needed to join a campaign.
CREATE TABLE IF NOT EXISTS friendships (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_low     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    user_high    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    requested_by INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status       TEXT NOT NULL CHECK (status IN ('pending', 'accepted', 'blocked')),
    created_at   TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at   TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    CHECK (user_low < user_high),
    CHECK (requested_by IN (user_low, user_high)),
    UNIQUE (user_low, user_high)
);
CREATE INDEX IF NOT EXISTS idx_friendships_high ON friendships (user_high, status);
ALTER TABLE friendships ENABLE ROW LEVEL SECURITY;               -- like every table: no direct access through Supabase's data API

-- Who can open a profile gains 'friends'; the bio and the featured characters can be narrower than the page itself.
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_profile_visibility_check;
ALTER TABLE users ADD CONSTRAINT users_profile_visibility_check CHECK (profile_visibility IN ('members', 'shared', 'friends', 'private'));
ALTER TABLE users ADD COLUMN IF NOT EXISTS bio_visibility TEXT NOT NULL DEFAULT 'profile' CHECK (bio_visibility IN ('profile', 'friends', 'private'));
ALTER TABLE users ADD COLUMN IF NOT EXISTS showcase_visibility TEXT NOT NULL DEFAULT 'profile' CHECK (showcase_visibility IN ('profile', 'friends', 'private'));
