-- DL-150: saved attacks on a character.  An attack is a name, a to-hit bonus and a damage roll ("1d8+3", one kind of die
-- plus a flat bonus, stored normalised; empty when the attack has no damage roll) with an optional damage type.
-- The details page turns each into two roll buttons that go through the normal dice route.
CREATE TABLE character_attacks (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    character_id INTEGER NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    position     INTEGER NOT NULL DEFAULT 0,
    name         TEXT NOT NULL,
    attack_bonus INTEGER NOT NULL DEFAULT 0,
    damage       TEXT NOT NULL DEFAULT '',
    damage_type  TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_character_attacks_character ON character_attacks (character_id, position);

ALTER TABLE character_attacks ENABLE ROW LEVEL SECURITY;        -- like every table: no direct access through Supabase's data API
