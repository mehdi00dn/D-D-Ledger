-- Quest tracker on the campaign Home page (DL-151): a short list the DM keeps.  Hidden quests are for the DM's eyes only.
CREATE TABLE IF NOT EXISTS quests (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
    title       TEXT NOT NULL,
    details     TEXT,
    done        BOOLEAN NOT NULL DEFAULT FALSE,
    hidden      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS idx_quests_campaign ON quests (campaign_id, id);

ALTER TABLE quests ENABLE ROW LEVEL SECURITY;                   -- like every table: no direct access through Supabase's data API
