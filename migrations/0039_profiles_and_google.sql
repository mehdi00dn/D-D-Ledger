-- Proper profiles and Google sign-in (DL-97 first step).
-- google_sub: Google's stable id for the person, set the first time they sign in with Google.
-- profile_visibility: who can open /u/<username>.  'members' = any signed-in user, 'shared' = people who share a campaign
-- with the owner (default), 'private' = only the owner.
-- profile_showcase: up to a handful of the owner's player characters shown on the profile.  Only name, class, level and
-- portrait are ever shown, never the campaign they belong to.
ALTER TABLE users ADD COLUMN google_sub TEXT;
CREATE UNIQUE INDEX idx_users_google_sub ON users (google_sub) WHERE google_sub IS NOT NULL;
ALTER TABLE users ADD COLUMN profile_visibility TEXT NOT NULL DEFAULT 'shared'
    CHECK (profile_visibility IN ('members', 'shared', 'private'));

CREATE TABLE profile_showcase (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- the data layer reads an id back from every insert
    user_id      INTEGER NOT NULL REFERENCES users(id)      ON DELETE CASCADE,
    character_id INTEGER NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    position     INTEGER NOT NULL DEFAULT 0,
    UNIQUE (user_id, character_id)
);
CREATE INDEX idx_profile_showcase_character ON profile_showcase(character_id);
ALTER TABLE profile_showcase ENABLE ROW LEVEL SECURITY;          -- like every table: no direct access through Supabase's data API
