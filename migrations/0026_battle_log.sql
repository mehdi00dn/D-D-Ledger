-- A short running log of what happens in a campaign's battle (damage, healing, conditions, downed / died / revived, rounds ...).
-- Only the latest entries are kept (the app prunes it), so it never grows.  `public_text` is what Players see for events
-- about enemies (no numbers); NULL means "same as text" and an empty string means "hidden from Players".
CREATE TABLE battle_log (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
    kind        TEXT NOT NULL,
    text        TEXT NOT NULL,
    public_text TEXT,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX idx_battle_log_campaign ON battle_log (campaign_id, id);

ALTER TABLE battle_log ENABLE ROW LEVEL SECURITY;               -- like every table: no direct access through Supabase's data API
