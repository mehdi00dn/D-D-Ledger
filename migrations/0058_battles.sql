-- Durable battles (DL-13).
--
-- Before: a participant belonged to a campaign only through its character (a join on every query), the round and whose
-- turn it is lived on the campaign row, and a familiar token on a linked map needed a hidden throw-away character.
-- Now:
--   * battle_participants carries its own campaign_id (scoped without a join, and a campaign's battle cannot reach another's);
--   * a battles row per campaign holds the round and the current turn;
--   * a participant can stand on its own: character_id may be NULL and the snap_* columns hold what it needs (a familiar's
--     name, picture, hit points, armour and whether it counts as an NPC).  Characters and monsters stay linked to their sheet.
-- Every existing row is converted in place; hidden familiar characters are folded into their participants and removed.

CREATE TABLE IF NOT EXISTS battles (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id         INTEGER NOT NULL UNIQUE REFERENCES campaigns(id) ON DELETE CASCADE,
    round               INTEGER NOT NULL DEFAULT 1,
    turn_participant_id INTEGER REFERENCES battle_participants(id) ON DELETE SET NULL,
    updated_at          TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
ALTER TABLE battles ENABLE ROW LEVEL SECURITY;                  -- like every table: no direct access through Supabase's data API

INSERT INTO battles (campaign_id, round, turn_participant_id)
SELECT id, COALESCE(battle_round, 1), battle_turn_id FROM campaigns
ON CONFLICT (campaign_id) DO NOTHING;

ALTER TABLE battle_participants ADD COLUMN IF NOT EXISTS campaign_id   INTEGER REFERENCES campaigns(id) ON DELETE CASCADE;
ALTER TABLE battle_participants ADD COLUMN IF NOT EXISTS snap_name     TEXT;
ALTER TABLE battle_participants ADD COLUMN IF NOT EXISTS snap_max_hp   INTEGER;
ALTER TABLE battle_participants ADD COLUMN IF NOT EXISTS snap_ac       INTEGER;
ALTER TABLE battle_participants ADD COLUMN IF NOT EXISTS snap_icon     TEXT;
ALTER TABLE battle_participants ADD COLUMN IF NOT EXISTS snap_is_npc   INTEGER NOT NULL DEFAULT 0 CHECK (snap_is_npc IN (0, 1));
ALTER TABLE battle_participants ADD COLUMN IF NOT EXISTS snap_owner_id INTEGER REFERENCES users(id) ON DELETE SET NULL;

UPDATE battle_participants bp SET campaign_id = c.campaign_id
  FROM characters c WHERE c.id = bp.character_id AND bp.campaign_id IS NULL;

-- Hidden familiar characters become self-contained participants.
UPDATE battle_participants bp SET snap_name = c.name, snap_max_hp = c.max_hp, snap_ac = c.armor_class,
       snap_icon = c.familiar_icon_key, snap_is_npc = COALESCE(c.is_npc, 0), snap_owner_id = c.created_by
  FROM characters c WHERE c.id = bp.character_id AND c.is_temp_familiar = 1;

ALTER TABLE battle_participants ALTER COLUMN character_id DROP NOT NULL;
UPDATE battle_participants SET character_id = NULL WHERE snap_name IS NOT NULL;
DELETE FROM characters WHERE is_temp_familiar = 1;

-- A participant with no campaign had no character or a character with no campaign: it cannot belong to any battle.
DELETE FROM battle_participants WHERE campaign_id IS NULL;
ALTER TABLE battle_participants ALTER COLUMN campaign_id SET NOT NULL;
ALTER TABLE battle_participants ADD CONSTRAINT battle_participants_self_or_character CHECK (character_id IS NOT NULL OR snap_name IS NOT NULL);
CREATE INDEX IF NOT EXISTS idx_battle_participants_campaign ON battle_participants (campaign_id, sort_order, id);
CREATE INDEX IF NOT EXISTS idx_battles_turn ON battles (turn_participant_id);

-- Transitional: the previous version of the app, still running for a few minutes while this is deployed, inserts a
-- participant without a campaign_id.  It is filled in from the character, so that version keeps working.  The new code
-- always sets campaign_id; a later migration can drop this trigger.
CREATE OR REPLACE FUNCTION battle_participant_fill_campaign() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.campaign_id IS NULL AND NEW.character_id IS NOT NULL THEN
        SELECT campaign_id INTO NEW.campaign_id FROM characters WHERE id = NEW.character_id;
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER trg_battle_participant_fill_campaign BEFORE INSERT ON battle_participants
    FOR EACH ROW EXECUTE FUNCTION battle_participant_fill_campaign();

