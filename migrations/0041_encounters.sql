-- Encounter builder (DL-147): a saved list of monsters the DM can weigh against the party's XP budget and send to the battle.
-- Name, challenge and XP are copied from the stat block when saved, so a list never needs the rules API to be shown.
CREATE TABLE IF NOT EXISTS encounters (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
    created_by  INTEGER REFERENCES users(id) ON DELETE SET NULL,
    name        TEXT NOT NULL,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS idx_encounters_campaign ON encounters (campaign_id, id);

CREATE TABLE IF NOT EXISTS encounter_monsters (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id INTEGER NOT NULL REFERENCES encounters(id) ON DELETE CASCADE,
    ref          TEXT NOT NULL,                       -- 'monsters/goblin-warrior'
    name         TEXT NOT NULL,
    cr           TEXT NOT NULL DEFAULT '0',
    xp           INTEGER NOT NULL DEFAULT 0,
    count        INTEGER NOT NULL DEFAULT 1,
    position     INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_encounter_monsters_encounter ON encounter_monsters (encounter_id, position);

ALTER TABLE encounters ENABLE ROW LEVEL SECURITY;               -- like every table: no direct access through Supabase's data API
