-- A short, campaign-wide activity feed: who joined or left, and which characters, factions and maps were added or removed.
-- The actor is stored as a user id (not a name) so a deleted account simply shows as "a former member".
CREATE TABLE campaign_activity (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
    user_id     INTEGER REFERENCES users(id) ON DELETE SET NULL,
    kind        TEXT NOT NULL,
    text        TEXT NOT NULL,
    link        TEXT,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX idx_campaign_activity_campaign ON campaign_activity (campaign_id, id);

ALTER TABLE campaign_activity ENABLE ROW LEVEL SECURITY;        -- like every table: no direct access through Supabase's data API
