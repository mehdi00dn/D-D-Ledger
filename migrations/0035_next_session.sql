-- Session scheduling: the DM sets the next session (a UTC time and a short note); members answer yes / maybe / no.
-- Changing the time clears the answers so nobody is counted for a time they never saw.
ALTER TABLE campaigns ADD COLUMN next_session_at   TIMESTAMP(0);
ALTER TABLE campaigns ADD COLUMN next_session_note TEXT;

CREATE TABLE session_rsvps (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
    user_id     INTEGER NOT NULL REFERENCES users(id)     ON DELETE CASCADE,
    status      TEXT NOT NULL CHECK (status IN ('yes', 'maybe', 'no')),
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    UNIQUE (campaign_id, user_id)
);
CREATE INDEX idx_session_rsvps_user ON session_rsvps(user_id);
ALTER TABLE session_rsvps ENABLE ROW LEVEL SECURITY;
