-- Party treasury ledger (DL-148): the purse is the sum of its entries.  Each entry holds a signed change per coin
-- (positive = coins in, negative = coins out), who made it, an optional character it was for, and why.
CREATE TABLE IF NOT EXISTS treasury_entries (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id  INTEGER NOT NULL REFERENCES campaigns(id) ON DELETE CASCADE,
    created_by   INTEGER REFERENCES users(id) ON DELETE SET NULL,
    character_id INTEGER REFERENCES characters(id) ON DELETE SET NULL,
    cp           INTEGER NOT NULL DEFAULT 0,
    sp           INTEGER NOT NULL DEFAULT 0,
    ep           INTEGER NOT NULL DEFAULT 0,
    gp           INTEGER NOT NULL DEFAULT 0,
    pp           INTEGER NOT NULL DEFAULT 0,
    note         TEXT NOT NULL,
    created_at   TIMESTAMP(0) NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC')
);
CREATE INDEX IF NOT EXISTS idx_treasury_campaign ON treasury_entries (campaign_id, id);

ALTER TABLE treasury_entries ENABLE ROW LEVEL SECURITY;         -- like every table: no direct access through Supabase's data API
